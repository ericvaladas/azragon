type Shape = { poly: Poly; minX: number; maxX: number; minY: number; maxY: number };
const shape = (poly: Poly): Shape => ({
  poly,
  minX: Math.min(...poly.map((p) => p[0])),
  maxX: Math.max(...poly.map((p) => p[0])),
  minY: Math.min(...poly.map((p) => p[1])),
  maxY: Math.max(...poly.map((p) => p[1])),
});
const LAND_SHAPES = LAND.map(shape);
const WATER_SHAPES = WATER.map(shape);

/** Even-odd ray cast, after a bounding-box reject. */
function inside(s: Shape, x: number, y: number): boolean {
  if (x < s.minX || x > s.maxX || y < s.minY || y > s.maxY) return false;
  const p = s.poly;
  let hit = false;
  for (let i = 0, j = p.length - 1; i < p.length; j = i++) {
    const [xi, yi] = p[i]!;
    const [xj, yj] = p[j]!;
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) hit = !hit;
  }
  return hit;
}

/** Whether the point at (lon, lat) degrees is land on the simplified map; lon wraps, lat is clamped to ±90. */
export function landAt(lon: number, lat: number): boolean {
  const x = ((((lon + 180) % 360) + 360) % 360) - 180;
  const y = Math.max(-90, Math.min(90, lat));
  return LAND_SHAPES.some((s) => inside(s, x, y)) && !WATER_SHAPES.some((s) => inside(s, x, y));
}
